@click.command("set-password")
@click.argument("username")
@click.option("--password", prompt=True, hide_input=True, confirmation_prompt=True)
def set_password_command(username, password):
    """Reset a user's password from the command line (e.g. when locked out)."""
    from .auth import hash_password
    conn = get_db()
    if conn.execute("SELECT 1 FROM account WHERE username=?", (username,)).fetchone() is None:
        raise click.ClickException(f"No user named {username}")
    conn.execute("UPDATE account SET password_hash=?, active=1 WHERE username=?", (hash_password(password), username))
    conn.commit()
    click.echo(f"Password updated for {username}")


def _table_exists(conn, table):
    if is_postgres(conn):
        return conn.execute("SELECT 1 FROM pg_tables WHERE schemaname='public' AND tablename=?", (table,)).fetchone() is not None
    return conn.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (table,)).fetchone() is not None


def _has_column(conn, table, column):
    if is_postgres(conn):
        return conn.execute("SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name=? "
                            "AND column_name=?", (table, column)).fetchone() is not None
    return any(r[1] == column for r in conn.execute(f"PRAGMA table_info({table})"))


def ensure_schema():
    """Before the first request of each process: if the database is initialised but lacks a table that a newer
    version of the code added, create it (init_db only adds what is missing and never drops data). This makes a
    plain redeploy enough on Vercel. A completely empty database is left alone; the login page explains it."""
    app = current_app._get_current_object()
    if app.extensions.get("igi_schema_ok") or request.endpoint == "static":
        return
    conn = get_db()
    try:
        if is_postgres(conn):
            existing = {r[0] for r in conn.execute("SELECT tablename FROM pg_tables WHERE schemaname='public'")}
        else:
            existing = {r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        missing = [t for t in ALL_TABLES if t != "approval_request" and t not in existing]
        if "sample" in existing and not _has_column(conn, "sample", "collection_id"):
            # A database built for nomenclature v2 (35-character IDs, root tubes). It cannot be upgraded in place.
            if app.config.get("DEMO_MODE"):
                from .demo import reset_demo
                app.logger.warning("Database is on nomenclature v2; rebuilding the demo for v2.1")
                reset_demo(conn, app.config["DEMO_PASSWORD"])
            else:
                app.logger.error("Database is on nomenclature v2. Back it up and rebuild it (flask init-db on an empty file), "
                                 "or run the v2-final tag of the code.")
                return
        elif missing and "account" in existing:
            app.logger.warning("Creating missing tables: %s", ", ".join(missing))
            init_db(conn)
        app.extensions["igi_schema_ok"] = True
    except Exception as e:      # e.g. two cold starts racing on CREATE TABLE; the next request tries again
        conn.rollback()
        app.logger.error("Schema check failed: %s", e)


def init_app(app):
    app.before_request(ensure_schema)
    app.teardown_appcontext(close_db)
    app.cli.add_command(init_db_command)
    app.cli.add_command(create_user_command)
    app.cli.add_command(set_password_command)
    app.cli.add_command(seed_demo_command)
    app.cli.add_command(demo_reset_command)
