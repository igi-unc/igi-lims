"""Database access.

Two backends behind one small API, chosen by configuration:

* SQLite (default): ``DATABASE`` is a file path. Used for local work and tests.
* PostgreSQL: ``DATABASE_URL`` (``LIMS_DATABASE_URL`` in the environment) is a
  ``postgresql://`` URL, e.g. a Supabase pooler connection string. Used when the
  app runs somewhere without a persistent disk (Vercel).

The rest of the code is written against the sqlite3 conventions (``?``
placeholders, ``conn.execute(...).fetchone()``, ``row["col"]``, ``cur.lastrowid``,
``executescript``). ``PgConnection`` translates those for psycopg, so the service
layer and views do not know which backend is in use. SQL that is specific to one
engine is listed in ``_pg_sql`` below; keep new SQL within that dialect.
"""
import os
import re
import sqlite3
import click
from flask import current_app, g, request

from . import seed as seed_module, seed_attributes

# Tables whose integer key is generated by the database (the code reads cur.lastrowid after INSERT): table -> key column.
SERIAL_KEYS = {"label_print": "id", "print_job": "id", "collection": "collection_id", "sample_correction": "id", "custody_event": "id", "data_file": "id",
               "audit_log": "id", "attribute_definition": "id", "attachment": "id"}
SERIAL_TABLES = tuple(SERIAL_KEYS)
# Every table, in dependency order, for reset_db.
ALL_TABLES = ("label_print", "print_job", "sample_correction", "sample_attribute", "attachment", "audit_log", "data_file", "custody_event", "sample", "collection", "participant", "id_counter",
              "account", "attribute_definition", "derivation_rule", "code_list", "approval_request")


# ----------------------------------------------------------------------------- PostgreSQL adapter

_UTC_NOW_SQLITE = "strftime('%Y-%m-%dT%H:%M:%SZ','now')"
_UTC_NOW_PG = """to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')"""
_INSERT_RE = re.compile(r"^\s*INSERT\s+(?:OR\s+IGNORE\s+)?INTO\s+(\w+)", re.I)


def _pg_sql(sql, named=False, with_params=True):
    """Rewrite the SQLite dialect used in this code base for PostgreSQL."""
    sql = sql.replace(_UTC_NOW_SQLITE, _UTC_NOW_PG)
    if with_params:
        sql = sql.replace("%", "%%")                   # literal percent signs (LIKE ? || '%') next to %s placeholders
    if named:
        sql = re.sub(r"(?<![:\w]):([A-Za-z_]\w*)", r"%(\1)s", sql)
    else:
        sql = sql.replace("?", "%s")
    sql = re.sub(r"\bLIKE\b", "ILIKE", sql)            # SQLite LIKE is case-insensitive
    if re.match(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO", sql, re.I):
        sql = re.sub(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", sql, flags=re.I).rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return sql


def _pg_schema(script):
    """schema.sql is written for SQLite; adapt the DDL."""
    s = re.sub(r"^\s*PRAGMA[^\n]*\n", "", script, flags=re.M)
    s = s.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s)
    s = s.replace(_UTC_NOW_SQLITE, _UTC_NOW_PG)
    # byte-order sorting of IDs, as in SQLite, regardless of the server's locale
    s = re.sub(r"\b(sample_id|parent_id|root_id|participant_id)(\s+)TEXT\b", r'\1\2TEXT COLLATE "C"', s)
    return s


class Row:
    """Minimal sqlite3.Row equivalent: index or name access, keys(), iteration over values, dict(row)."""
    __slots__ = ("_keys", "_vals")

    def __init__(self, keys, vals):
        self._keys, self._vals = keys, vals

    def __getitem__(self, k):
        if isinstance(k, int):
            return self._vals[k]
        return self._vals[self._keys.index(k)]

    def keys(self):
        return list(self._keys)

    def __iter__(self):
        return iter(self._vals)

    def __len__(self):
        return len(self._vals)

    def __repr__(self):
        return "Row(%r)" % dict(zip(self._keys, self._vals))


class PgCursor:
    def __init__(self, cur, lastrowid=None):
        self._cur = cur
        self.lastrowid = lastrowid
        self._keys = [d.name for d in cur.description] if cur.description else []

    def _wrap(self, t):
        return None if t is None else Row(self._keys, t)

    def fetchone(self):
        return self._wrap(self._cur.fetchone())

    def fetchall(self):
        return [Row(self._keys, t) for t in self._cur.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())

    @property
    def rowcount(self):
        return self._cur.rowcount


class PgConnection:
    backend = "postgres"

    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql, params=()):
        named = isinstance(params, dict)
        m = _INSERT_RE.match(sql)
        want_id = bool(m) and m.group(1).lower() in SERIAL_TABLES and "RETURNING" not in sql.upper()
        with_params = bool(params) or named
        pg = _pg_sql(sql, named, with_params)
        if want_id:
            pg = pg.rstrip().rstrip(";") + " RETURNING " + SERIAL_KEYS[m.group(1).lower()]
        cur = self.raw.cursor()
        cur.execute(pg, params if with_params else None)
        lastrowid = None
        if want_id:
            row = cur.fetchone()
            lastrowid = row[0] if row else None
        return PgCursor(cur, lastrowid)

    def executescript(self, script):
        self.raw.execute(_pg_schema(script))

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        pass   # returned to the pool in close_db


class SqliteConnection(sqlite3.Connection):
    backend = "sqlite"


_pool = None


def _pg_pool(url):
    global _pool
    if _pool is None or _pool.conninfo != url:
        from psycopg_pool import ConnectionPool
        kwargs = {"prepare_threshold": None}          # pgbouncer/Supabase transaction pooling cannot use prepared statements
        if "sslmode=" not in url and "host=/" not in url and "localhost" not in url and "127.0.0.1" not in url:
            kwargs["sslmode"] = "require"
        _pool = ConnectionPool(url, min_size=0, max_size=int(os.environ.get("LIMS_PG_POOL", "2")),
                               kwargs=kwargs, open=True)
    return _pool


def get_db():
    if "db" not in g:
        url = current_app.config.get("DATABASE_URL")
        if url:
            raw = _pg_pool(url).getconn()
            g.db = PgConnection(raw)
        else:
            path = current_app.config["DATABASE"]
            os.makedirs(os.path.dirname(path), exist_ok=True)
            conn = sqlite3.connect(path, detect_types=0, timeout=10, factory=SqliteConnection)
            conn.row_factory = sqlite3.Row
            conn.execute("PRAGMA foreign_keys = ON")
            conn.execute("PRAGMA journal_mode = WAL")
            conn.execute("PRAGMA busy_timeout = 10000")
            g.db = conn
    return g.db


def close_db(e=None):
    conn = g.pop("db", None)
    if conn is None:
        return
    if isinstance(conn, PgConnection):
        try:
            conn.raw.rollback()
        finally:
            _pool.putconn(conn.raw)
    else:
        conn.close()


def is_postgres(conn=None):
    return getattr(conn or get_db(), "backend", "sqlite") == "postgres"


ROLES = ("admin", "user", "viewer", "printer")


def _migrate(conn):
    """Small in-place migrations for databases created by earlier versions."""
    if _table_exists(conn, "sample") and not _has_column(conn, "sample", "serial"):
        conn.execute("ALTER TABLE sample ADD COLUMN serial INTEGER")
    if _table_exists(conn, "print_job") and not _has_column(conn, "print_job", "reprint_reason"):
        conn.execute("ALTER TABLE print_job ADD COLUMN reprint_reason TEXT")
    if is_postgres(conn):
        if conn.execute("SELECT 1 FROM pg_tables WHERE schemaname='public' AND tablename='account'").fetchone():
            roles = ",".join(f"'{r}'" for r in ROLES)
            conn.execute("ALTER TABLE account DROP CONSTRAINT IF EXISTS account_role_check")
            conn.execute(f"ALTER TABLE account ADD CONSTRAINT account_role_check CHECK (role IN ({roles}))")
        return
    acct = conn.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name='account'").fetchone()
    if acct and "'printer'" not in acct["sql"]:      # widen the role CHECK (SQLite cannot alter constraints)
        conn.executescript("""
            ALTER TABLE account RENAME TO account_old;
            CREATE TABLE account (
                username TEXT PRIMARY KEY, display_name TEXT NOT NULL, initials TEXT NOT NULL, password_hash TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('admin','user','viewer','printer')),
                active INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')));
            INSERT INTO account SELECT username, display_name, initials, password_hash, role, active, created_at FROM account_old;
            DROP TABLE account_old;
        """)
    names = {r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    if "user" in names and "account" not in names:
        conn.execute("ALTER TABLE user RENAME TO account")          # "user" is reserved in PostgreSQL
    if "audit_log" in names:
        cols = {r[1] for r in conn.execute("PRAGMA table_info(audit_log)")}
        if "reason" not in cols:
            conn.execute("ALTER TABLE audit_log ADD COLUMN reason TEXT")
            if "approval_id" in cols:   # keep the old approval numbers readable after the queue was removed
                conn.execute("UPDATE audit_log SET reason='approved in request #' || approval_id WHERE approval_id IS NOT NULL")
    row = conn.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name='attribute_definition'").fetchone()
    if row and "'list'" not in row["sql"]:
        conn.executescript("""
            ALTER TABLE attribute_definition RENAME TO attribute_definition_old;
            CREATE TABLE attribute_definition (
                id INTEGER PRIMARY KEY AUTOINCREMENT, scope TEXT NOT NULL CHECK (scope IN ('fraction','material','all')),
                code TEXT NOT NULL, key TEXT NOT NULL, label TEXT NOT NULL,
                type TEXT NOT NULL CHECK (type IN ('text','number','bool','choice','list','date','datetime')),
                unit TEXT, choices TEXT, required INTEGER NOT NULL DEFAULT 0, sort_order INTEGER NOT NULL DEFAULT 0,
                active INTEGER NOT NULL DEFAULT 1, UNIQUE (scope, code, key));
            INSERT INTO attribute_definition SELECT * FROM attribute_definition_old;
            DROP TABLE attribute_definition_old;
        """)


def _lock_down_postgres(conn):
    """Supabase exposes every table in the public schema through its REST API (PostgREST) to anyone holding
    the project's anon key. This app talks to Postgres directly as the table owner and never uses that API,
    so turn row level security on with no policies (the owner is unaffected; everyone else sees nothing)
    and take away the REST roles' grants as well. Harmless on a plain Postgres where those roles do not exist."""
    tables = [t for t in ALL_TABLES
              if conn.execute("SELECT 1 FROM pg_tables WHERE schemaname='public' AND tablename=?", (t,)).fetchone()]
    for t in tables:
        conn.execute(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY")
    rest_roles = [r[0] for r in conn.execute("SELECT rolname FROM pg_roles WHERE rolname IN ('anon','authenticated')")]
    if rest_roles:
        roles = ", ".join(rest_roles)
        conn.execute(f"REVOKE ALL ON ALL TABLES IN SCHEMA public FROM {roles}")
        conn.execute(f"REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM {roles}")
        conn.execute(f"ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM {roles}")
        conn.execute(f"ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM {roles}")


def serial_digits():
    return int(current_app.config.get("LIMS_NUMBER_DIGITS", 9))


def serial_max():
    return 10 ** serial_digits() - 1


def format_serial(n):
    """The LIMS number as printed: zero-padded to LIMS_NUMBER_DIGITS."""
    return f"{int(n):0{serial_digits()}d}" if n is not None else ""


def _number_unnumbered_samples(conn):
    """Give tubes from before LIMS numbers existed a number, in the order they were created, and set the counter."""
    conn.execute("INSERT OR IGNORE INTO id_counter(name, value) VALUES ('sample_serial', -1)")
    rows = conn.execute("SELECT sample_id FROM sample WHERE serial IS NULL ORDER BY record_created_at, sample_id").fetchall()
    if rows:
        conn.execute("UPDATE id_counter SET value = (SELECT COALESCE(MAX(serial), -1) FROM sample) "
                     "WHERE name='sample_serial' AND value < (SELECT COALESCE(MAX(serial), -1) FROM sample)")
        for r in rows:
            conn.execute("UPDATE id_counter SET value = value + 1 WHERE name='sample_serial'")
            n = conn.execute("SELECT value FROM id_counter WHERE name='sample_serial'").fetchone()[0]
            conn.execute("UPDATE sample SET serial=? WHERE sample_id=?", (n, r["sample_id"]))


def init_db(conn=None):
    conn = conn or get_db()
    _migrate(conn)
    with current_app.open_resource("schema.sql") as f:
        conn.executescript(f.read().decode("utf8"))
    seed_module.seed(conn)
    _number_unnumbered_samples(conn)
    seed_attributes.seed(conn)
    if is_postgres(conn):
        _lock_down_postgres(conn)
    conn.commit()


def reset_db(conn=None):
    """Drop every table and rebuild an empty, seeded schema (demo instances; tests)."""
    conn = conn or get_db()
    cascade = " CASCADE" if is_postgres(conn) else ""
    for t in ALL_TABLES:
        conn.execute(f"DROP TABLE IF EXISTS {t}{cascade}")
    conn.commit()
    init_db(conn)


def describe():
    url = current_app.config.get("DATABASE_URL")
    if url:
        return "PostgreSQL " + re.sub(r"://([^:/]+):[^@]*@", r"://\1:***@", url)
    return "SQLite " + current_app.config["DATABASE"]


